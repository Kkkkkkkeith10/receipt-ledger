import type { RequestHandler } from '@sveltejs/kit';
import { receipts, expenseReports } from '$lib/server/db';
import { eq, and, gte, lte, sql, desc } from 'drizzle-orm';
import { getFiscalYear, getFiscalYearRange, formatFiscalYear } from '$lib/utils/fiscal';
import { calculateGSTFromInclusive } from '$lib/utils/gst';
import { getCategoryName, getCategoryIcon, getCategoryColor, DEFAULT_CATEGORIES } from '$lib/categories';
import type { ExpenseReport, CategorySummary, MonthlySummary, QuarterlySummary } from '$lib/types';
import { convertToHKD, type SupportedCurrency } from '$lib/utils/format';
import { requireAuth } from '$lib/server/auth/helpers';

// Bump when report aggregation logic changes so stale cached reports are recomputed.
const REPORT_VERSION = 3;

export const GET: RequestHandler = async (event) => {
    await requireAuth(event);
    const { params, locals } = event;
    const DB = locals.DB;
    if (!DB) return new Response('Database not available', { status: 500 });

    try {
        const fy = parseInt(params.fy ?? String(getFiscalYear()));
        if (isNaN(fy) || fy < 2000 || fy > 2100) {
            return new Response('Invalid fiscal year', { status: 400 });
        }

        // Check for cached report
        const cached = await DB.select()
            .from(expenseReports)
            .where(eq(expenseReports.fiscalYear, fy))
            .limit(1);

        if (cached.length > 0) {
            const cacheAge = Date.now() - new Date(cached[0].generatedAt ?? 0).getTime();
            const cachedReport = cached[0].reportData as (ExpenseReport & { version?: number }) | null;
            // Use cache only if fresh AND generated by the current aggregation logic.
            if (
                cacheAge < 60 * 60 * 1000 &&
                cachedReport &&
                cachedReport.version === REPORT_VERSION
            ) {
                return new Response(JSON.stringify(cachedReport), {
                    headers: { 'content-type': 'application/json' }
                });
            }
        }

        // Generate fresh report
        const report = await generateReport(DB, fy);

        // Cache the report
        const reportId = `FY${fy}`;
        await DB.insert(expenseReports)
            .values({
                id: reportId,
                fiscalYear: fy,
                reportData: report as any
            })
            .onConflictDoUpdate({
                target: expenseReports.id,
                set: {
                    reportData: report as any,
                    updatedAt: new Date().toISOString()
                }
            });

        return new Response(JSON.stringify(report), {
            headers: { 'content-type': 'application/json' }
        });
    } catch (error) {
        console.error('Error generating report:', error);
        return new Response(JSON.stringify({ error: 'Failed to generate report', details: error instanceof Error ? error.message : String(error) }), {
            status: 500,
            headers: { 'content-type': 'application/json' }
        });
    }
};

async function generateReport(DB: any, fy: number): Promise<ExpenseReport> {
    const { start, end } = getFiscalYearRange(fy);
    const startStr = start.toISOString().split('T')[0];
    const endStr = end.toISOString().split('T')[0];

    // Fetch all approved, non-archived receipts for the fiscal year.
    // Draft / pending / rejected receipts are excluded from financial totals.
    const data = await DB.select()
        .from(receipts)
        .where(and(
            gte(receipts.date, startStr),
            lte(receipts.date, endStr),
            eq(receipts.status, 'approved'),
            sql`COALESCE(json_extract(${receipts.receiptData}, '$.archived'), 0) = 0`
        ))
        .orderBy(desc(receipts.date));

    const receiptList = data.map((row: any) => {
        const rd = row.receiptData as any;
        return {
            id: row.id,
            vendor: row.vendor ?? rd.vendor,
            originalAmount: Number(row.amount ?? rd.amount ?? 0),
            currency: (rd.currency ?? 'HKD') as SupportedCurrency,
            gstAmount: Number(rd.gstAmount ?? 0),
            netAmount: Number(rd.netAmount ?? 0),
            gstFree: rd.gstFree ?? false,
            date: row.date ?? rd.date,
            category: row.category ?? rd.category,
            taxDeductible: Boolean(row.taxDeductible ?? rd.taxDeductible ?? true)
        };
    });

    // Calculate totals
    let totalExpenses = 0;
    let totalGst = 0;
    let taxDeductibleTotal = 0;
    let nonDeductibleTotal = 0;

    // Category breakdown
    const categoryMap = new Map<string, { total: number; gst: number; count: number }>();

    // Monthly breakdown
    const monthlyMap = new Map<number, { total: number; gst: number; count: number }>();

    // Vendor totals
    const vendorMap = new Map<string, { total: number; count: number }>();

    for (const receipt of receiptList) {
        // Normalize all receipt amounts to HKD so totals are comparable across currencies.
        const amount = convertToHKD(receipt.originalAmount, receipt.currency);
        const gstBreakdown = receipt.gstFree
            ? { gst: 0, net: amount }
            : calculateGSTFromInclusive(amount);
        const gst = receipt.gstAmount
            ? convertToHKD(receipt.gstAmount, receipt.currency)
            : gstBreakdown.gst;

        totalExpenses += amount;
        totalGst += gst;

        if (receipt.taxDeductible) {
            taxDeductibleTotal += amount;
        } else {
            nonDeductibleTotal += amount;
        }

        // Category
        const catId = receipt.category || 'other';
        const catData = categoryMap.get(catId) ?? { total: 0, gst: 0, count: 0 };
        catData.total += amount;
        catData.gst += gst;
        catData.count += 1;
        categoryMap.set(catId, catData);

        // Monthly
        const receiptDate = new Date(receipt.date);
        const month = receiptDate.getMonth() + 1; // 1-12
        const monthData = monthlyMap.get(month) ?? { total: 0, gst: 0, count: 0 };
        monthData.total += amount;
        monthData.gst += gst;
        monthData.count += 1;
        monthlyMap.set(month, monthData);

        // Vendor
        const vendorData = vendorMap.get(receipt.vendor) ?? { total: 0, count: 0 };
        vendorData.total += amount;
        vendorData.count += 1;
        vendorMap.set(receipt.vendor, vendorData);
    }

    // Build category breakdown
    const categoryBreakdown: CategorySummary[] = Array.from(categoryMap.entries())
        .map(([catId, data]) => ({
            categoryId: catId,
            categoryName: getCategoryName(catId),
            categoryIcon: getCategoryIcon(catId),
            categoryColor: getCategoryColor(catId),
            totalAmount: Math.round(data.total * 100) / 100,
            gstAmount: Math.round(data.gst * 100) / 100,
            netAmount: Math.round((data.total - data.gst) * 100) / 100,
            receiptCount: data.count,
            percentOfTotal: totalExpenses > 0 ? Math.round((data.total / totalExpenses) * 1000) / 10 : 0
        }))
        .sort((a, b) => b.totalAmount - a.totalAmount);

    // Build monthly breakdown
    const monthNames = [
        '',
        'January',
        'February',
        'March',
        'April',
        'May',
        'June',
        'July',
        'August',
        'September',
        'October',
        'November',
        'December'
    ];
    const monthlyBreakdown: MonthlySummary[] = [];
    for (let m = 1; m <= 12; m++) {
        const data = monthlyMap.get(m) ?? { total: 0, gst: 0, count: 0 };
        // Fiscal month: July = 1
        const fyMonth = m >= 7 ? m - 6 : m + 6;
        monthlyBreakdown.push({
            month: m,
            monthName: monthNames[m],
            fiscalMonth: fyMonth,
            totalAmount: Math.round(data.total * 100) / 100,
            gstAmount: Math.round(data.gst * 100) / 100,
            receiptCount: data.count
        });
    }
    // Sort by fiscal month
    monthlyBreakdown.sort((a, b) => a.fiscalMonth - b.fiscalMonth);

    // Build quarterly breakdown
    const quarterlyBreakdown: QuarterlySummary[] = [
        { quarter: 1, quarterName: 'Q1 (Jul-Sep)', months: [7, 8, 9] },
        { quarter: 2, quarterName: 'Q2 (Oct-Dec)', months: [10, 11, 12] },
        { quarter: 3, quarterName: 'Q3 (Jan-Mar)', months: [1, 2, 3] },
        { quarter: 4, quarterName: 'Q4 (Apr-Jun)', months: [4, 5, 6] }
    ].map((q) => {
        let total = 0;
        let gst = 0;
        let count = 0;
        for (const m of (q as any).months) {
            const data = monthlyMap.get(m) ?? { total: 0, gst: 0, count: 0 };
            total += data.total;
            gst += data.gst;
            count += data.count;
        }
        return {
            quarter: q.quarter,
            quarterName: q.quarterName,
            startDate: '',
            endDate: '',
            totalAmount: Math.round(total * 100) / 100,
            gstAmount: Math.round(gst * 100) / 100,
            netAmount: Math.round((total - gst) * 100) / 100,
            receiptCount: count
        };
    });

    // Top vendors
    const topVendors = Array.from(vendorMap.entries())
        .map(([vendor, data]) => ({
            vendor,
            total: Math.round(data.total * 100) / 100,
            count: data.count
        }))
        .sort((a, b) => b.total - a.total)
        .slice(0, 10);

    const report: ExpenseReport = {
        fiscalYear: fy,
        fiscalYearDisplay: formatFiscalYear(fy),
        startDate: startStr,
        endDate: endStr,
        totalExpenses: Math.round(totalExpenses * 100) / 100,
        totalGst: Math.round(totalGst * 100) / 100,
        totalNetExpenses: Math.round((totalExpenses - totalGst) * 100) / 100,
        receiptCount: receiptList.length,
        categoryBreakdown,
        monthlyBreakdown,
        quarterlyBreakdown,
        taxDeductibleTotal: Math.round(taxDeductibleTotal * 100) / 100,
        nonDeductibleTotal: Math.round(nonDeductibleTotal * 100) / 100,
        topVendors,
        generatedAt: new Date().toISOString(),
        version: REPORT_VERSION
    } as ExpenseReport & { version: number };

    return report;
}
